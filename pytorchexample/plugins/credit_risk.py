"""pytorchexample.plugins.credit_risk: Credit Risk tabular dataset plugin.

Dataset
-------
Uses the UCI "Give Me Some Credit" / Kaggle credit-scoring dataset (or a
synthetic stand-in generated by SDV so you can run without a Kaggle token).

Features (10 after preprocessing):
    RevolvingUtilization, Age, NumberOfTime30-59DaysPastDueNotWorse,
    DebtRatio, MonthlyIncome, NumberOfOpenCreditLinesAndLoans,
    NumberOfTimes90DaysLate, NumberRealEstateLoansOrLines,
    NumberOfTime60-89DaysPastDueNotWorse, NumberOfDependents

Target: SeriousDlqin2yrs (0 = good, 1 = default) -> binary classification.

Experiment mapping
------------------
    E1  Centralised baseline - server trains on full dataset
    E2  Standard FL (FedAvg, IID)    -> non_iid=False
    E3  Non-IID FL (FedProx)         -> non_iid=True
    E4  DP-FL                        -> non_iid=False, use_dp=True
    E5  FedSynAI (DP + Synthetic)    -> non_iid=True,  use_synthetic=True
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Tuple

import numpy as np
import pandas as pd
from sklearn.datasets import make_classification
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, TensorDataset

from pytorchexample.plugins.interfaces import FedSynAIPlugin, register_plugin


# ------------------------------------------------------------------ #
# Tabular MLP                                                          #
# ------------------------------------------------------------------ #

class TabularMLP(nn.Module):
    """3-layer MLP for binary tabular classification."""

    def __init__(self, input_dim: int = 10, hidden_dim: int = 64, num_classes: int = 2):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(hidden_dim // 2, num_classes),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)


# ------------------------------------------------------------------ #
# Dataset helpers                                                       #
# ------------------------------------------------------------------ #

FEATURE_COLS = [
    "RevolvingUtilizationOfUnsecuredLines",
    "age",
    "NumberOfTime30-59DaysPastDueNotWorse",
    "DebtRatio",
    "MonthlyIncome",
    "NumberOfOpenCreditLinesAndLoans",
    "NumberOfTimes90DaysLate",
    "NumberRealEstateLoansOrLines",
    "NumberOfTime60-89DaysPastDueNotWorse",
    "NumberOfDependents",
]
TARGET_COL = "SeriousDlqin2yrs"
INPUT_DIM = len(FEATURE_COLS)


def _resolve_csv_path() -> Path:
    """Find or define the path to cs-training.csv."""
    custom_path = os.environ.get("CREDIT_RISK_CSV")
    if custom_path:
        return Path(custom_path)
    # Check standard project locations
    project_root = Path(__file__).resolve().parent.parent.parent
    if (project_root / "data" / "cs-training.csv").exists():
        return project_root / "data" / "cs-training.csv"
    if (project_root / "cs-training.csv").exists():
        return project_root / "cs-training.csv"
    if Path("data/cs-training.csv").exists():
        return Path("data/cs-training.csv").resolve()
    # Default cache target inside project data/ directory
    return project_root / "data" / "cs-training.csv"


def _ensure_dataset_exists(csv_path: Path) -> pd.DataFrame:
    """Load cs-training.csv or create and cache a learnable credit dataset once on disk."""
    if csv_path.exists():
        df = pd.read_csv(csv_path)
        if "Unnamed: 0" in df.columns:
            df = df.drop(columns=["Unnamed: 0"])
        return df

    csv_path.parent.mkdir(parents=True, exist_ok=True)
    print(f"[CreditRisk] '{csv_path}' not found. Creating and caching learnable credit dataset (4,000 rows)...")

    X, y = make_classification(
        n_samples=4000,
        n_features=10,
        n_informative=7,
        n_redundant=2,
        weights=[0.7, 0.3],  # Realistic 70/30 credit default class balance
        random_state=42,
    )
    df = pd.DataFrame(X, columns=FEATURE_COLS)
    df[TARGET_COL] = y
    df.to_csv(csv_path, index=False)
    print(f"[CreditRisk] Cached dataset saved to {csv_path}")
    return df


def _load_or_generate_df() -> pd.DataFrame:
    """Load credit CSV or create and cache a learnable stand-in once on disk."""
    csv_path = _resolve_csv_path()
    df = _ensure_dataset_exists(csv_path)

    # Basic cleaning & standardization
    df = df[FEATURE_COLS + [TARGET_COL]].dropna()
    df[FEATURE_COLS] = (df[FEATURE_COLS] - df[FEATURE_COLS].mean()) / (
        df[FEATURE_COLS].std() + 1e-8
    )
    return df.reset_index(drop=True)


def _df_to_tensors(df: pd.DataFrame) -> Tuple[torch.Tensor, torch.Tensor]:
    X = torch.tensor(df[FEATURE_COLS].values, dtype=torch.float32)
    y = torch.tensor(df[TARGET_COL].values, dtype=torch.long)
    return X, y



def _partition_iid(
    df: pd.DataFrame, partition_id: int, num_partitions: int
) -> pd.DataFrame:
    """Even IID split."""
    chunk = len(df) // num_partitions
    start = partition_id * chunk
    end = start + chunk if partition_id < num_partitions - 1 else len(df)
    return df.iloc[start:end].reset_index(drop=True)


def _partition_non_iid(
    df: pd.DataFrame, partition_id: int, num_partitions: int, alpha: float = 0.5
) -> pd.DataFrame:
    """Dirichlet-based non-IID split (label skew)."""
    rng = np.random.default_rng(42 + partition_id)
    classes = df[TARGET_COL].unique()
    selected_indices: list[int] = []
    for cls in classes:
        cls_indices = df.index[df[TARGET_COL] == cls].tolist()
        proportions = rng.dirichlet(np.ones(num_partitions) * alpha)
        n_samples = int(proportions[partition_id] * len(cls_indices))
        chosen = rng.choice(cls_indices, size=min(n_samples, len(cls_indices)), replace=False)
        selected_indices.extend(chosen.tolist())
    return df.loc[selected_indices].reset_index(drop=True)


# ------------------------------------------------------------------ #
# Plugin implementation                                                 #
# ------------------------------------------------------------------ #

@register_plugin
class CreditRiskPlugin(FedSynAIPlugin):
    """FedSynAI plugin for binary credit-default prediction."""

    _name = "credit_risk"   # must match pyproject.toml plugin-name

    # -------------------------------------------------------------- #
    # FedSynAIPlugin interface                                         #
    # -------------------------------------------------------------- #

    @property
    def name(self) -> str:
        return self._name

    @property
    def num_classes(self) -> int:
        return 2

    @property
    def input_dim(self) -> int:
        return INPUT_DIM

    def build_model(self) -> nn.Module:
        return TabularMLP(input_dim=INPUT_DIM, num_classes=self.num_classes)

    def load_partition(
        self,
        partition_id: int,
        num_partitions: int,
        batch_size: int,
        non_iid: bool = False,
        use_synthetic: bool = False,
    ) -> Tuple[DataLoader, DataLoader]:
        df = _load_or_generate_df()
        if non_iid:
            part = _partition_non_iid(df, partition_id, num_partitions)
        else:
            part = _partition_iid(df, partition_id, num_partitions)

        # 80 / 20 train-val split
        split = int(0.8 * len(part))
        train_df, val_df = part.iloc[:split], part.iloc[split:]

        # E5: Augment training partition with CTGAN synthetic rows
        if use_synthetic:
            from pytorchexample.synth_engine import augment_partition
            train_df = augment_partition(
                train_df,
                target_col=TARGET_COL,
                synth_ratio=1.0,        # doubles the training set
                model_type="ctgan",
            )

        X_tr, y_tr = _df_to_tensors(train_df)
        X_val, y_val = _df_to_tensors(val_df)

        train_loader = DataLoader(
            TensorDataset(X_tr, y_tr), batch_size=batch_size, shuffle=True
        )
        val_loader = DataLoader(TensorDataset(X_val, y_val), batch_size=batch_size)
        return train_loader, val_loader


    def load_centralized_dataset(self, batch_size: int = 128) -> DataLoader:
        """Use the last 20 % of the full dataset as the server-side test set."""
        df = _load_or_generate_df()
        split = int(0.8 * len(df))
        test_df = df.iloc[split:].reset_index(drop=True)
        X, y = _df_to_tensors(test_df)
        return DataLoader(TensorDataset(X, y), batch_size=batch_size)
